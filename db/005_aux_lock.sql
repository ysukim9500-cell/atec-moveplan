-- ============================================================================
-- 005_aux_lock.sql — 부속 시트 쓰기를 관리자로 좁힌다
--
-- 부속 시트 화면은 뺐는데 정책은 «관리자 또는 팀장 누구나» 로 남아 있었다.
-- 화면이 없으니 팀장이 REST 로 한 해치를 덮어써도 아무도 눈치채지 못하고,
-- mp_audit 에도 남지 않는다. 지금 이 표에 쓰는 곳은 데이터 이관 화면뿐이고
-- 그건 관리자 전용이다.
--
-- 읽기는 그대로 둔다 — 나중에 화면을 되살릴 때 필요하다.
--
-- 여러 번 실행해도 안전하다.
-- ============================================================================

drop policy if exists mp_w on mp_aux;
create policy mp_w on mp_aux for all
  using      (mp_is_admin())
  with check (mp_is_admin());
